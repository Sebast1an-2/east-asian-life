function visibleTags(player) {
  return TAG_GROUPS.filter(g => g.tags.some(t => player.tags.includes(t)) && !(g.except || []).some(t => player.tags.includes(t)))
    .map(g => ({label: g.label, recent: player.history.reduce((last,h,i) => h.addTags?.some(t => g.tags.includes(t)) ? i : last, -1)}))
    .sort((a,b) => b.recent - a.recent).slice(0,8).map(g => g.label);
}
